SELECT /* lemmesee:discovery:my.s.indexes */ TABLE_NAME, INDEX_NAME, MIN(NON_UNIQUE) AS NON_UNIQUE,
       GROUP_CONCAT(COALESCE(COLUMN_NAME, '(expression)') ORDER BY SEQ_IN_INDEX SEPARATOR '\t') AS cols
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE()
GROUP BY TABLE_NAME, INDEX_NAME
ORDER BY TABLE_NAME, INDEX_NAME
